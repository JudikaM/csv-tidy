"""AC-58: the contract changes of 2.0.0 (docs/STABILITY.md, "Changes made in 2.0.0").

The product is called Datakrit: report ``tool.name`` is ``datakrit`` and report
``schema_version`` is ``3``; nothing else in the reports changed. Profiles keep
``schema_version = 1``: every example profile gives the same results as in 1.2.0. The
aliases deprecated in 1.0.0 are removed.
"""

import hashlib
import importlib.util
import inspect
import json
from pathlib import Path

import pytest
from conftest import EXAMPLES, run_cli

import datakrit
from datakrit import clean_file, export_clean, load_profile, run_batch, select_inputs

PROFILE = EXAMPLES / "profiles" / "transactions-id.toml"
FIXABLE = EXAMPLES / "transactions_fixable.csv"
CLEAN_ARGS = ("--trim", "amount", "--trim", "date")
# Fingerprints of the results of 1.2.0 (the last release under the old name), made with its
# published wheel by the same functions as below. Only the covered surface is compared:
# report schema_version and tool, and human wording (not covered), are left out.
RESULTS_1X = Path(__file__).with_name("results_1_2_0.json")
WORDING = {"message", "suggestion", "headline", "next_steps"}


def normalized(report, names):
    """The report without ``schema_version``, ``tool``, and wording; paths become names."""

    def walk(value):
        if isinstance(value, dict):
            return {k: walk(v) for k, v in value.items() if k not in WORDING}
        if isinstance(value, list):
            return [walk(v) for v in value]
        if isinstance(value, str):
            return names.get(value, value)
        return value

    top = {k: v for k, v in report.items() if k not in ("schema_version", "tool")}
    return walk(top)


def fingerprint(data):
    text = json.dumps(data, sort_keys=True, ensure_ascii=True)
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def path_names(paths):
    """Every way a report may spell an example path, mapped to its name below examples/."""
    names = {}
    for path in paths:
        name = path.relative_to(path.parents[1] if path.parent.name == "profiles" else path.parent)
        for spelling in (str(path), str(path.resolve()), path.as_posix()):
            names[spelling] = name.as_posix()
    return names


def without_comments(toml_text):
    return "\n".join(line for line in toml_text.splitlines() if not line.startswith("#"))


# --------------------------------------------------------------- profiles keep working


def current_results():
    csvs = sorted(EXAMPLES.glob("*.csv"))
    profiles = sorted((EXAMPLES / "profiles").glob("*.toml"))
    names = path_names([*csvs, *profiles])
    results = {}
    for profile in profiles:
        for csv in csvs:
            case = f"{profile.name} {csv.name}"
            entry = {}
            for command in ("check", "clean"):
                ran = run_cli(command, str(csv), "--profile", str(profile), "--format", "json")
                report = json.loads(ran.out)
                entry[command] = [ran.code, fingerprint(normalized(report, names))]
            cleaned = clean_file(csv, profile)
            entry["csv"] = fingerprint(cleaned.csv_text())
            entry["output_profile"] = fingerprint(without_comments(cleaned.output_profile_toml()))
            results[case] = entry
        for action in ("check", "clean"):
            ran = run_cli(
                "batch", action, str(EXAMPLES), "--profile", str(profile), "--format", "json"
            )
            report = json.loads(ran.out)
            results[f"{profile.name} batch {action}"] = [
                ran.code,
                fingerprint(normalized(report, names)),
            ]
    return results


def test_example_profiles_give_the_same_results_as_1_2_0():
    expected = json.loads(RESULTS_1X.read_text(encoding="utf-8"))
    assert expected.pop("version") == "1.2.0"
    current = current_results()
    assert sorted(current) == sorted(expected)
    differ = [case for case in expected if current[case] != expected[case]]
    assert differ == []


def test_example_profiles_load_with_schema_version_1():
    for profile in sorted((EXAMPLES / "profiles").glob("*.toml")):
        text = profile.read_text(encoding="utf-8")
        assert text.count("schema_version = 1") == 1
        assert load_profile(profile).path == str(profile)


def test_output_profiles_still_carry_schema_version_1(tmp_path):
    result = run_cli(
        "clean", str(FIXABLE), "--profile", str(PROFILE), *CLEAN_ARGS, "--apply",
        "--output", str(tmp_path / "out.csv"), "--output-profile", str(tmp_path / "out.toml"),
    )  # fmt: skip
    assert result.code == 0, result.err
    text = (tmp_path / "out.toml").read_text(encoding="utf-8")
    assert "\nschema_version = 1\n" in f"\n{text}"
    assert text.startswith(f"# Generated by datakrit {datakrit.__version__} from")
    assert load_profile(tmp_path / "out.toml").path == str(tmp_path / "out.toml")


# ------------------------------------------------------------------ reports: new name


def test_reports_name_datakrit_with_schema_version_3(tmp_path):
    check = json.loads(run_cli("check", str(FIXABLE), "--format", "json").out)
    clean = json.loads(run_cli("clean", str(FIXABLE), "--format", "json").out)
    batch = json.loads(run_cli("batch", "check", str(FIXABLE), "--format", "json").out)
    for report in (check, clean, batch):
        assert report["schema_version"] == 3
        assert report["tool"] == {"name": "datakrit", "version": datakrit.__version__}
    text = run_cli("check", str(FIXABLE)).out
    assert text.startswith(f"Datakrit {datakrit.__version__} - check")


# ----------------------------------------------------------- removed names and aliases


@pytest.mark.parametrize(
    ("args", "old", "new"),
    [
        (("check", str(FIXABLE), "--schema", str(PROFILE)), "--schema", "--profile"),
        (("clean", str(FIXABLE), "--schema=x.toml"), "--schema", "--profile"),
        (
            ("clean", str(FIXABLE), "--output-schema", "o.toml"),
            "--output-schema",
            "--output-profile",
        ),
        (
            ("batch", "clean", str(FIXABLE), "--output-schemas"),
            "--output-schemas",
            "--output-profiles",
        ),
        (("batch", "check", str(FIXABLE), "--schema", "p.toml"), "--schema", "--profile"),
    ],
)
def test_options_removed_in_2_0_0_are_usage_errors_that_name_the_new_option(args, old, new):
    result = run_cli(*args)
    assert result.code == 2 and result.out == ""
    assert f"error: {old} was removed in 2.0.0; use {new}" in result.err


def test_a_removed_name_after_the_end_of_options_is_not_an_option():
    result = run_cli("check", "--", "--schema")
    assert result.code == 2 and "was removed" not in result.err


def test_python_keywords_removed_in_2_0_0(tmp_path):
    assert "output_schema" not in inspect.signature(export_clean).parameters
    assert "output_schemas" not in inspect.signature(run_batch).parameters
    result = clean_file(FIXABLE, PROFILE, overrides=datakrit.Overrides(trim=("amount", "date")))
    with pytest.raises(TypeError, match="output_schema"):
        export_clean(result, tmp_path / "a.csv", output_schema=tmp_path / "a.toml")
    assert not (tmp_path / "a.csv").exists()
    with pytest.raises(TypeError, match="output_schemas"):
        run_batch("clean", select_inputs([FIXABLE]), PROFILE, output_schemas=False)


def test_the_error_class_and_the_module_have_the_new_name():
    assert "DatakritError" in datakrit.__all__
    assert issubclass(datakrit.ProfileError, datakrit.DatakritError)
    assert issubclass(datakrit.InputError, datakrit.DatakritError)
    assert issubclass(datakrit.OutputError, datakrit.DatakritError)
    assert not any("tidy" in name.lower() for name in dir(datakrit))
    assert importlib.util.find_spec("datakrit") is not None


def test_program_names(tmp_path):
    result = run_cli("--version")
    assert result.out.strip() == f"datakrit {datakrit.__version__}"
    usage = run_cli("--help").out
    assert usage.startswith("usage: datakrit ")
    error = run_cli("check", str(tmp_path / "missing.csv"))
    assert error.code == 2 and error.err.startswith("datakrit: error: ")
